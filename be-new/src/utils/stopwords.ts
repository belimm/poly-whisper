/**
 * Filter out irrelevant keywords using stopwords list
 */
export function filterStopwords(keywords: string[]): string[] {
   if (!Array.isArray(keywords)) return [];

   return keywords.filter((keyword) => {
      if (typeof keyword !== 'string') return false;

      const normalized = keyword.toLowerCase().trim();

      // Skip empty strings or single characters (with exceptions)
      if (normalized.length < 2) return false;

      // Skip if in stopwords list
      if (STOPWORDS.has(normalized)) return false;

      // Skip if it's just a number
      if (/^\d+$/.test(normalized)) return false;

      return true;
   });
}

/**
 * Check if a single keyword should be filtered out
 */
export function isStopword(keyword: string): boolean {
   if (typeof keyword !== 'string') return true;

   const normalized = keyword.toLowerCase().trim();

   if (normalized.length < 2) return true;
   if (/^\d+$/.test(normalized)) return true;

   return STOPWORDS.has(normalized);
}

